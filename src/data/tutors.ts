export function getTutorBySlug(slug: string): Tutor | undefined {
  return tutors.find((tutor) => tutor.slug === slug);
}

export function getAllTutorSlugs(): string[] {
  return tutors.map((tutor) => tutor.slug);
}

export function getTutorsBySubject(subjectName: string): Tutor[] {
  return tutors.filter((tutor) =>
    tutor.subjects.some(
      (sub) => sub.toLowerCase() === subjectName.toLowerCase()
    )
  );
}
